"""Turn ddc/ddc_template.html into js/ddc_template.js, which the generator (index.html) loads.

Run after editing the template:  python tools/build_template.py

The page cannot read the template file itself when opened from disk (browsers block file:// reads), so the
template is shipped as a JavaScript string. The script also makes the template safe for the SAS job server:
  - non-ASCII characters are escaped (\\uXXXX inside <script>, &#x..; elsewhere)
  - a dollar sign anywhere fails the build (the job server deletes text between two dollar signs)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "ddc", "ddc_template.html")
OUT = os.path.join(ROOT, "js", "ddc_template.js")
BS = chr(92)


def asciify(text):
    out, pos = [], 0
    while True:
        start = text.find("<script", pos)
        end = text.find("</script>", start) if start >= 0 else -1
        chunk = text[pos:start if start >= 0 else len(text)]
        out.append("".join(c if ord(c) < 128 else "&#x%x;" % ord(c) for c in chunk))
        if start < 0:
            break
        out.append("".join(c if ord(c) < 128 else BS + "u%04x" % ord(c) for c in text[start:end]))
        pos = end
    return "".join(out)


def main():
    with open(SRC, encoding="utf-8") as f:
        text = f.read()
    if chr(36) in text:
        line = text[:text.index(chr(36))].count("\n") + 1
        sys.exit("ddc_template.html line %d: remove the dollar sign (the SAS job server would corrupt the page)" % line)
    for marker in ("/*@THEME@*/", "/*@/THEME@*/", "/*@BRAND@*/", "/*@/BRAND@*/"):
        if marker not in text:
            sys.exit("ddc_template.html: marker %s is missing" % marker)
    text = asciify(text)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/build_template.py from ddc/ddc_template.html - do not edit by hand. */\n")
        f.write("window.DDC_TEMPLATE = " + json.dumps(text) + ";\n")
    print("Wrote %s (%d characters)" % (OUT, len(text)))


if __name__ == "__main__":
    main()
